//DELETE A FLASH MESSAGE SUCCESS		
function delete_a_flash_message_success () {
var close_button = document.getElementsByClassName("close_button");
$('.flash_alert_success').remove();
};

//DELETE A FLASH MESSAGE WARNING			
function delete_a_flash_message_warning () {
var close_button = document.getElementsByClassName("close_button");
$('.flash_alert_warning').remove();
};

